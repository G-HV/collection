"""Automated email feed for a stock screener prototype.

This script is a simple starter for the "Automated email feed emulating an
automated screener" project in the Quantitative Finance section of the repo.

The program:
- defines a small candidate universe
- screens each symbol against a simple rule set
- builds a summary email body
- sends it via SMTP if configured

This is intentionally lightweight and dependency-free so it can be expanded into
an API-based or database-backed screener later.
"""

from __future__ import annotations

import json
import os
import smtplib
from dataclasses import dataclass
from email.message import EmailMessage
from typing import Dict, Iterable, List, Tuple


@dataclass
class StockSignal:
    symbol: str
    price: float
    moving_average: float
    volume: int
    signal: str


def sample_market_data() -> Dict[str, Dict[str, float | int]]:
    """Return a small sample universe for local testing.

    Replace this with API calls or a database query in a production version.
    """
    return {
        "AAPL": {"price": 214.32, "moving_average": 208.40, "volume": 6800000},
        "MSFT": {"price": 432.15, "moving_average": 425.10, "volume": 3200000},
        "NVDA": {"price": 126.90, "moving_average": 118.75, "volume": 9100000},
        "META": {"price": 515.00, "moving_average": 505.50, "volume": 2500000},
        "AMZN": {"price": 178.45, "moving_average": 174.30, "volume": 4300000},
    }


def screen_stocks(data: Dict[str, Dict[str, float | int]]) -> List[StockSignal]:
    """Apply a basic stock-screening strategy.

    A stock passes when:
    - price is above its moving average
    - volume exceeds a minimum threshold
    """
    results: List[StockSignal] = []
    min_volume = 3_000_000

    for symbol, stats in data.items():
        price = float(stats["price"])
        moving_average = float(stats["moving_average"])
        volume = int(stats["volume"])

        if price > moving_average and volume > min_volume:
            signal = "BUY/REVIEW"
        else:
            signal = "WATCH"

        results.append(
            StockSignal(
                symbol=symbol,
                price=price,
                moving_average=moving_average,
                volume=volume,
                signal=signal,
            )
        )

    return sorted(results, key=lambda item: item.symbol)


def build_email_body(signals: Iterable[StockSignal]) -> str:
    """Format the screener report for email delivery."""
    summary_lines = [
        "Automated Screener Summary",
        "========================",
        "",
        "Symbol | Price | 20d MA | Volume | Signal",
        "-------|-------|--------|--------|--------",
    ]

    for signal in signals:
        summary_lines.append(
            f"{signal.symbol:<6} | ${signal.price:>8.2f} | ${signal.moving_average:>8.2f} | "
            f"{signal.volume:>10,} | {signal.signal}"
        )

    summary_lines.extend(
        [
            "",
            "This message was generated by the automated email screener prototype.",
        ]
    )

    return "\n".join(summary_lines)


def send_email(subject: str, body: str, to_email: str | None = None) -> None:
    """Send the generated screener report via SMTP.

    Requires environment variables:
    - SMTP_SERVER
    - SMTP_PORT
    - SMTP_USERNAME
    - SMTP_PASSWORD
    - FROM_EMAIL
    """
    smtp_server = os.getenv("SMTP_SERVER")
    smtp_port = int(os.getenv("SMTP_PORT", "587"))
    username = os.getenv("SMTP_USERNAME")
    password = os.getenv("SMTP_PASSWORD")
    from_email = os.getenv("FROM_EMAIL", "noreply@example.com")

    if not smtp_server or not username or not password:
        print("SMTP not configured. Printing email body instead:\n")
        print(f"Subject: {subject}\n")
        print(body)
        return

    recipient = to_email or os.getenv("TO_EMAIL", from_email)

    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = from_email
    msg["To"] = recipient
    msg.set_content(body)

    with smtplib.SMTP(smtp_server, smtp_port) as server:
        server.starttls()
        server.login(username, password)
        server.send_message(msg)

    print(f"Email sent to {recipient}")


def main() -> None:
    """Generate a screener summary and email it."""
    market_data = sample_market_data()
    signals = screen_stocks(market_data)
    body = build_email_body(signals)

    print(body)
    send_email(
        subject="Daily Quantitative Finance Screener Update",
        body=body,
        to_email=os.getenv("TO_EMAIL"),
    )


if __name__ == "__main__":
    main()
